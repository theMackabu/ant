import re
import sys

DENIED_TOKENS = (
  "DISPATCH", "goto *", "JIT_OSR_BACK_EDGE", "entry_fp", "vm_result", "sv_leave", "L_RETURN",
  "suspended", "tc_this", "tc_argc", "NEXT(*", "sv_sync_frame_locals", "JIT_OSR_FINISH",
  "SUSPEND_YIELD", "RETURN_VALUE", "COMPLETE_FRAME",
)

ASSIGNED = re.compile(r"(?<![\w.>])(ip|frame|func|lp)\s*(=(?!=)|\+=|-=|\+\+|--)")
GOTO = re.compile(r"\bgoto\s+(\w+)")
STATIC_FN = re.compile(r"^(?:__attribute__\(\([^)]*\)\)\s*)?static\b[^;=]*?\b(\w+)\s*\(", re.M)
LABEL = re.compile(r"^\s*L_(\w+):\s*\{", re.M)


def block_at(text, start):
  depth = 0
  for i in range(start, len(text)):
    if text[i] == "{":
      depth += 1
    elif text[i] == "}":
      depth -= 1
      if depth == 0:
        return text[start:i + 1]
  raise SystemExit("generic_step.py: unbalanced block")


def main():
  with open(sys.argv[1], encoding="utf-8") as f:
    text = f.read()
  begin = text.index("static const void *dispatch[OP__COUNT]")
  end = text.index("sv_throw: {", begin)
  statics = {m.group(1) for m in STATIC_FN.finditer(text[:begin])}
  region = text[begin:end]

  cases = []
  for m in LABEL.finditer(region):
    name = m.group(1)
    body = block_at(region, m.end() - 1)
    if f"NEXT(OP_{name})" not in body and "goto sv_throw" not in body:
      continue
    if any(token in body for token in DENIED_TOKENS):
      continue
    if ASSIGNED.search(body) or any(g != "sv_throw" for g in GOTO.findall(body)):
      continue
    if any(re.search(rf"\b{fn}\s*\(", body) for fn in statics):
      continue
    cases.append((name, body))

  print("// Generated by meson/generic_step.py from src/silver/engine.c.")
  print("#if defined(SV_GENERIC_STEP_CASES)")
  for name, body in cases:
    print(f"case OP_{name}: {body}")
  print("#elif defined(SV_GENERIC_STEP_TABLE)")
  for name, _ in cases:
    print(f"[OP_{name}] = true,")
  print("#endif")


main()
