import os
import re
import sys

DENIED_TOKENS = (
  "DISPATCH", "goto *", "JIT_OSR_BACK_EDGE", "entry_fp", "vm_result", "sv_leave", "L_RETURN",
  "suspended", "tc_this", "tc_argc", "NEXT(*", "VM_RELOAD_FRAME", "VM_LEAVE", "JIT_OSR_FINISH",
  "SUSPEND_YIELD", "RETURN_VALUE", "COMPLETE_FRAME",
)

ASSIGNED = re.compile(r"(?<![\w.>])(ip|frame|func|lp)\s*(=(?!=)|\+=|-=|\+\+|--)")
GOTO = re.compile(r"\bgoto\s+(\w+)")
STATIC_FN = re.compile(r"^(?:__attribute__\(\([^)]*\)\)\s*)?static\b[^;=]*?\b(\w+)\s*\(", re.M)
LABEL = re.compile(r"^\s*L_(\w+):[ \t]*(\{|\S.*;[ \t]*$)", re.M)


def block_at(text, start):
  depth = 0
  for i in range(start, len(text)):
    if text[i] == "{":
      depth += 1
    elif text[i] == "}":
      depth -= 1
      if depth == 0:
        return text[start:i + 1]
  raise SystemExit("generic_step.py: unbalanced block")


def skip_reason(name, body, statics):
  if f"NEXT(OP_{name})" not in body and "VM_THROW" not in body:
    return "no NEXT"
  token = next((t for t in DENIED_TOKENS if t in body), None)
  if token:
    return f"token {token}"
  assigned = ASSIGNED.search(body)
  if assigned:
    return f"assigns {assigned.group(1)}"
  label = next((g for g in GOTO.findall(body) if g != "sv_throw"), None)
  if label:
    return f"goto {label}"
  static = next((fn for fn in sorted(statics) if re.search(rf"\b{fn}\s*\(", body)), None)
  if static:
    return f"calls static {static}"
  return None


def repo_path(path):
  root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
  return os.path.relpath(os.path.abspath(path), root)


def check_expected(engine, source, path, lines):
  with open(path, encoding="utf-8") as f:
    expected = [line.rstrip("\n") for line in f if line.strip()]
  if expected == lines:
    return
  was, now = set(expected), set(lines)
  sys.stderr.write(f"generic_step.py: generic-step ops differ from {repo_path(path)}\n")
  for line in sorted(was - now):
    sys.stderr.write(f"  - {line}\n")
  for line in sorted(now - was):
    sys.stderr.write(f"  + {line}\n")
  sys.stderr.write("review the changed handlers, then run: python3 meson/generic_step.py "
                   f"{repo_path(engine)} {repo_path(source)} {repo_path(path)} --update\n")
  raise SystemExit(1)


def main():
  engine, source, ops_path = sys.argv[1], sys.argv[2], sys.argv[3]
  with open(engine, encoding="utf-8") as f:
    text = f.read()
  statics = {m.group(1) for m in STATIC_FN.finditer(text[:text.index("static const void *dispatch[OP__COUNT]")])}
  with open(source, encoding="utf-8") as f:
    region = f.read()

  cases, lines = [], []
  for m in LABEL.finditer(region):
    name = m.group(1)
    body = block_at(region, m.start(2)) if m.group(2) == "{" else f"{{ {m.group(2).strip()} }}"
    reason = skip_reason(name, body, statics)
    lines.append(f"{name} skip: {reason}" if reason else name)
    if not reason:
      cases.append((name, body))

  if "--update" in sys.argv[4:]:
    with open(ops_path, "w", encoding="utf-8") as f:
      f.write("\n".join(lines) + "\n")
    return
  check_expected(engine, source, ops_path, lines)

  print("// Generated by meson/generic_step.py from src/silver/ops/handlers.h.")
  print("#if defined(SV_GENERIC_STEP_CASES)")
  for name, body in cases:
    print(f"case OP_{name}: {body}")
  print("#elif defined(SV_GENERIC_STEP_TABLE)")
  for name, _ in cases:
    print(f"[OP_{name}] = true,")
  print("#endif")


main()
