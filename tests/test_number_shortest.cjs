const assert = require('node:assert');

const cases = [
  [5e-324, "5e-324"],
  [-5e-324, "-5e-324"],
  [2.2250738585072014e-308, "2.2250738585072014e-308"],
  [2.225073858507201e-308, "2.225073858507201e-308"],
  [1.7976931348623157e308, "1.7976931348623157e+308"],
  [0.1, "0.1"],
  [0.2, "0.2"],
  [0.1 + 0.2, "0.30000000000000004"],
  [1 / 3, "0.3333333333333333"],
  [2 / 3, "0.6666666666666666"],
  [1e21, "1e+21"],
  [1e21 - 65536, "1e+21"],
  [999999999999999900000, "999999999999999900000"],
  [1e-7, "1e-7"],
  [1.5e-7, "1.5e-7"],
  [0.000001, "0.000001"],
  [0.0000015, "0.0000015"],
  [123e-20, "1.23e-18"],
  [2 ** 53, "9007199254740992"],
  [2 ** 53 + 2, "9007199254740994"],
  [2 ** 63, "9223372036854776000"],
  [2 ** 64, "18446744073709552000"],
  [2 ** -1074 * 3, "1.5e-323"],
  [2 ** 1023, "8.98846567431158e+307"],
  [-0, "0"],
  [4.35, "4.35"],
  [5e-7, "5e-7"],
  [9.5367431640625e-7, "9.5367431640625e-7"],
  [1e23, "1e+23"],
  [8.41e21, "8.41e+21"],
  [5.0e-324 * 2 ** 52, "2.2250738585072014e-308"],
  [0.3, "0.3"],
  [100, "100"],
  [1e100, "1e+100"],
  [123456789012345680000, "123456789012345680000"],
  [-1.2345678901234567e-300, "-1.2345678901234568e-300"],
  [4294967296.5, "4294967296.5"],
  [0.000123, "0.000123"],
];

for (const [value, expected] of cases) {
  assert.strictEqual(String(value), expected);
  assert.strictEqual(JSON.stringify([value]), '[' + (Number.isFinite(value) ? (Object.is(value, -0) ? '0' : expected) : 'null') + ']');
  assert.strictEqual(`${value}`, expected);
  assert.strictEqual(Number(expected), Object.is(value, -0) ? 0 : value);
}

