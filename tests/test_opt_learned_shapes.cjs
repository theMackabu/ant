const assert = require('node:assert');

function child() {
  function readX(o) { return o.x; }
  function run(objects, n) {
    let total = 0;
    for (let i = 0; i < n; i++) total += readX(objects[i % objects.length]);
    return total;
  }
  const two = [{ x: 1 }, { y: 0, x: 2 }];
  let total = 0;
  for (let i = 0; i < 300; i++) total += run(two, 100);
  const three = [...two, { z: 0, y: 0, x: 3 }];
  for (let i = 0; i < 300; i++) total += run(three, 99);
  console.log('learned', total);

  function readY(o) { return o.y; }
  function spin(objects, n) {
    let sum = 0;
    for (let i = 0; i < n; i++) sum += readY(objects[i % objects.length]);
    return sum;
  }
  const many = [];
  let grown = 0;
  for (let k = 0; k < 24; k++) {
    const o = {};
    for (let j = 0; j < k; j++) o['p' + j] = j;
    o.y = k;
    many.push(o);
    for (let i = 0; i < 40; i++) grown += spin(many, 50);
  }
  console.log('megamorphic', grown);
}

if (process.argv[2] === 'child') {
  child();
} else {
  const { spawnSync } = require('node:child_process');
  const base = { ...process.env };
  delete base.ANT_DEBUG;
  const run = (env, args = []) => spawnSync(process.execPath, [...args, __filename, 'child'], {
    encoding: 'utf8',
    env: { ...base, ...env, NO_COLOR: '1' },
    timeout: 120000, maxBuffer: 256 * 1024 * 1024,
  });
  const interp = run({}, ['--jitless']);
  assert.strictEqual(interp.status, 0, interp.stdout + interp.stderr);
  assert.match(interp.stdout, /^learned \d+\nmegamorphic \d+\n$/);
  const tier = (process.arch === 'arm64' || process.arch === 'x64') && (process.platform === 'darwin' || process.platform === 'linux');
  const modes = [
    ['default', 'dump/vm:op-warn'],
    ['verify', 'opt:verify dump/vm:op-warn'],
    ['force', 'opt:force,verify dump/vm:op-warn'],
    ['off', 'opt:off dump/vm:op-warn'],
  ];
  for (const [name, debug] of modes) {
    const child = run({ ANT_DEBUG: debug });
    assert.strictEqual(child.status, 0, `${name}: ${child.error || child.stdout + child.stderr.slice(-4000)}`);
    assert.strictEqual(child.stdout, interp.stdout, `${name}: output differs from --jitless`);
    if (tier && name !== 'off') {
      const shapeExits = (child.stderr.match(/func=readY .*kind=BadShape/g) || []).length;
      assert.ok(shapeExits <= 18, `${name}: shape exits must stop once the cache stops growing (${shapeExits})`);
      assert.doesNotMatch(child.stderr, /opt disabled func=readY /, `${name}: learning shapes must not disable the function`);
    }
    console.log(`PASS opt learned shapes ${name}`);
  }
  if (tier) {
    const dumped = run({ ANT_DEBUG: 'dump/opt:graph dump/vm:op-warn' });
    assert.strictEqual(dumped.status, 0, `dump: ${dumped.error || dumped.stderr.slice(-4000)}`);
    assert.match(dumped.stderr, /func=readX .*kind=BadShape/, 'readX must exit when the third shape appears');
    const graphs = dumped.stderr.split('[generated bytecode for function: ').filter((g) => g.startsWith('readX ') && g.includes('=== optimized'));
    assert.ok(graphs.length >= 2, 'readX must recompile after its shape exit');
    const last = graphs[graphs.length - 1].split('=== optimized')[1].split('=== ')[0];
    assert.doesNotMatch(last, /ProbePropertyCache/, 'the recompile must speculate on the shapes the cache learned');
    assert.match(last, /ShapeSwitch|CheckShape/, 'the recompile must check shapes');
    console.log('PASS opt learned shapes dump');
  }
}
