import { $ } from 'ant:shell';
import assert from 'node:assert';
assert.strictEqual(await $`echo $FOO`.env({ FOO: 'bar' }).text(), 'bar\n');
assert.strictEqual(await $`env | grep -c '^ONLY=1$'`.env({ ONLY: '1', PATH: process.env.PATH }).text(), '1\n');
assert.strictEqual(await $`pwd`.cwd('/tmp').text(), '/tmp\n');
assert.strictEqual(await $`echo ${{ raw: '$((1+2)) "a b"' }}`.text(), '3 a b\n');
const input = Buffer.from('hello from buffer\n');
assert.strictEqual(await $`cat < ${input}`.text(), 'hello from buffer\n');
assert.strictEqual(await $`wc -c < ${new Response('abcd')}`.text().then(t => t.trim()), '4');
assert.strictEqual(await $`tr a-z A-Z < ${new Blob(['blob'])}`.text(), 'BLOB');
const out = new Uint8Array(5);
await $`echo hello > ${out}`;
assert.strictEqual(Buffer.from(out).toString(), 'hello');
const lines = [];
for await (const line of $`printf 'a\nb\n'`.lines()) lines.push(line);
assert.deepStrictEqual(lines, ['a', 'b', '']);
assert.strictEqual($.escape('$(foo) `bar` "baz"'), '"\\$(foo) \\`bar\\` \\"baz\\""');
assert.strictEqual($.escape('plain'), 'plain');
assert.deepStrictEqual($.braces('echo {1,2,3}'), ['echo 1', 'echo 2', 'echo 3']);
let err;
try { await $`exit 3`; } catch (e) { err = e; }
assert.ok(err instanceof $.ShellError);
assert.strictEqual(err.constructor.name, 'ShellError');
assert.strictEqual(err.exitCode, 3);
const sh = new $.Shell();
sh.nothrow().cwd('/');
assert.strictEqual((await sh`pwd; exit 4`).exitCode, 4);
assert.strictEqual(await sh`pwd`.text(), '/\n');
assert.strictEqual((await $`exit 2`.throws(false)).exitCode, 2);
assert.strictEqual(await $`echo quiet`.quiet().text(), 'quiet\n');
assert.strictEqual(await $`printf %s ${'a'} | cat`.text('base64'), 'YQ==');
$.env({ GLOBAL_SHELL_VAR: 'yes', PATH: process.env.PATH });
assert.strictEqual(await $`echo $GLOBAL_SHELL_VAR`.text(), 'yes\n');
$.env();
assert.strictEqual(await $`echo "\${GLOBAL_SHELL_VAR:-unset}"`.text(), 'unset\n');
const { spawnSync } = await import('node:child_process');
const printing = spawnSync(process.execPath, ['-e', 'import("ant:shell").then(async ({ $ }) => { await $`echo loud`.quiet(false); await $`echo silent`; $.quiet(false); await $`echo global; echo err >&2`; })'], { encoding: 'utf8' });
assert.strictEqual(printing.stdout, 'loud\nglobal\n');
assert.strictEqual(printing.stderr, 'err\n');
console.log('ant:shell Bun-compatible API tests passed');
