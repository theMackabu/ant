const assert = require('node:assert');
const { spawnSync } = require('node:child_process');

function bytecodeLength(depth) {
  const expression = 'eval('.repeat(depth) + 'source' + ')'.repeat(depth);
  const source = `function nestedEval(source) { return ${expression}; } nestedEval('1');`;
  const result = spawnSync(process.execPath, ['-e', `(0, eval)(${JSON.stringify(source)})`], {
    encoding: 'utf8',
    env: { ...process.env, ANT_DEBUG: 'dump/vm:bytecode' }
  });
  if (result.error) throw result.error;
  assert.strictEqual(result.status, 0, result.stderr);
  const match = (result.stdout + result.stderr).match(
    /generated bytecode for function: nestedEval[^\n]*\nBytecode length: (\d+)/
  );
  assert.ok(match, 'missing nestedEval bytecode');
  return Number(match[1]);
}

const shallow = bytecodeLength(4);
const deep = bytecodeLength(8);
assert.ok(deep <= shallow * 3, `nested eval bytecode grew from ${shallow} to ${deep}`);
console.log('nested eval compilation tests passed');
