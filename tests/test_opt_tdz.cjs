function readK() { return K + 1; }
function loopK(n) {
  let s = 0;
  for (let i = 0; i < n; i++) s = (s + readK()) | 0;
  return s;
}
function storeT(n) {
  let s = 0;
  for (let i = 0; i < n; i++) { s = (s + i) | 0; T = s; }
  return s;
}
function* holder(z) {
  const reader = (n, advance) => {
    let s = 0;
    for (let i = 0; i < n; i++) {
      if (i === 0 && advance) advance();
      s += Z;
    }
    return s;
  };
  yield reader;
  let Z = z;
  yield 0;
}
function lateBinding() {
  const out = [];
  for (let r = 0; r < 300; r++) {
    const it = holder(r & 7);
    const reader = it.next().value;
    it.next();
    out.push(reader(2000));
  }
  for (let r = 0; r < 3; r++) {
    const it = holder(r + 1);
    const reader = it.next().value;
    out.push(attempt(reader, 1000, () => it.next()));
    const again = holder(9).next().value;
    out.push(attempt(again, 1000));
  }
  return out.slice(-8);
}
function perIteration(n) {
  let s = 0;
  for (let i = 0; i < n; i++) {
    const read = () => x;
    let x = i & 7;
    s += read();
  }
  return s;
}
function block(n) {
  let s = 0;
  for (let i = 0; i < n; i++) {
    {
      const get = () => y;
      let y = i;
      s += get() & 3;
    }
  }
  return s;
}

