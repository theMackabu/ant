function graphCase() {
  let G = 1;
  function hoisted(n) {
    let s = 0;
    for (let i = 0; i < n; i++) { s = (s + G) | 0; G = s & 7; }
    return s;
  }
  let t = 0;
  for (let i = 0; i < 3000; i++) t += hoisted(100);
  console.log(t, hoisted(1000));
}

if (process.argv[2] !== 'child') {
  const { spawnSync } = require('node:child_process');
  const base = { ...process.env };
  delete base.ANT_DEBUG;
  const run = (env, args = []) => spawnSync(process.execPath, [...args, __filename, 'child'], {
    encoding: 'utf8',
    env: { ...base, ...env, NO_COLOR: '1' },
    timeout: 120000, maxBuffer: 16 * 1024 * 1024,
  });
  const interp = run({}, ['--jitless']);
  assert.strictEqual(interp.status, 0, interp.stdout + interp.stderr);
  const tier = (process.arch === 'arm64' || process.arch === 'x64') && (process.platform === 'darwin' || process.platform === 'linux');
  for (const [name, debug] of [['default', 'dump/vm:op-warn'], ['verify', 'opt:verify dump/vm:op-warn'], ['force', 'opt:force opt:verify dump/vm:op-warn'], ['off', 'opt:off']]) {
    const child = run({ ANT_DEBUG: debug });
    assert.strictEqual(child.status, 0, `${name}: ${child.error || child.stdout + child.stderr}`);
    assert.strictEqual(child.stdout, interp.stdout, `${name}: output differs from the interpreter`);
    if (tier && name === 'default') {
      for (const fn of ['loopK', 'storeT', 'perIteration', 'block'])
        assert.match(child.stderr, new RegExp(`jit: opt compiled func=${fn} `), `${name}: ${fn} must compile on the opt tier`);
    }
    console.log(`PASS opt tdz ${name}`);
  }
  if (tier) {
    const graph = spawnSync(process.execPath, [__filename, 'graph'], {
      encoding: 'utf8', env: { ...base, ANT_DEBUG: 'dump/opt:graph', NO_COLOR: '1' }, timeout: 120000, maxBuffer: 64 * 1024 * 1024,
    });
    assert.strictEqual(graph.status, 0, graph.stdout + graph.stderr);
    const chunk = graph.stderr.split('[generated bytecode for function: ').filter((c) => c.startsWith('hoisted ')).pop() || '';
    const optimized = (chunk.split('=== optimized')[1] || '').split('=== allocation')[0].split('\n');
    const header = optimized.findIndex((line) => / loop:$/.test(line));
    const checks = optimized.map((line, i) => (/CheckUpvalueInitialized/.test(line) ? i : -1)).filter((i) => i >= 0);
    assert.ok(header > 0, 'hoisted has a loop');
    assert.ok(checks.length >= 1, 'the TDZ check of G is a node of its own');
    assert.ok(checks.every((i) => i < header), 'the TDZ checks of G run before the loop');
    assert.doesNotMatch(optimized.join('\n'), /LoadUpvalue \(v\d+\) \[fs/, 'loads of G carry no checks');
    console.log('PASS opt tdz hoisted');
  }
  console.log('ok');
}
