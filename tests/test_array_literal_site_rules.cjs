const assert = require('node:assert');
const { spawnSync } = require('node:child_process');

const large = Array.from({ length: 100 }, (_, i) => i).join(', ');
const cases = {
  smallFlat: { body: '[1, 2, 3]', site: false },
  leafObjects: { body: "[{ x: 1 }, { y: 'two' }, { z: null }]", site: false },
  emptyNested: { body: '[[], { a: 1 }]', site: false },
  nestedArray: { body: '[{ x: 1 }, [2]]', site: true },
  nestedInObject: { body: '[{ x: [1, 2] }]', site: true },
  largeFlat: { body: `[${large}]`, site: true },
};

const source = Object.entries(cases)
  .map(([name, { body }]) => `function ${name}() { return ${body}; } ${name}();`)
  .join('\n');

const result = spawnSync(process.execPath, ['-e', source], {
  encoding: 'utf8',
  env: { ...process.env, ANT_DEBUG: 'dump/vm:bytecode', NO_COLOR: '1' },
});
if (result.error) throw result.error;
assert.strictEqual(result.status, 0, result.stderr);

const dump = result.stdout + result.stderr;
for (const [name, { site }] of Object.entries(cases)) {
  const start = dump.indexOf(`generated bytecode for function: ${name} `);
  assert.ok(start >= 0, `missing bytecode for ${name}`);
  const end = dump.indexOf('[generated bytecode for function:', start + 1);
  const body = dump.slice(start, end < 0 ? undefined : end);
  assert.strictEqual(/\bARRAY_LITERAL\b/.test(body), site, `${name} literal site`);
}

console.log('ok');
